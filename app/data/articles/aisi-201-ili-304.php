<h2>Что учесть при обработке</h2>
<p>Обе марки аустенитные: хорошо штампуются, гнутся и свариваются стандартными методами. В состоянии поставки обе не магнитятся; после сильной холодной деформации возможна слабая намагниченность. Если нужна максимальная пластичность для вытяжки, заказывайте мягкое состояние ленты, для пружинных элементов — нагартованное. Подробнее в статье <a href="/spravochnik/nagartovannaya-i-myagkaya-lenta/">«Нагартованная и мягкая лента»</a>.</p>

<h2>Итог: что выбрать</h2>
