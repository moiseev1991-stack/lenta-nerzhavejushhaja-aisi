<h2>Почему 201 дешевле</h2>
<p>Никель — самый дорогой компонент нержавеющей стали. В AISI 201 его заметно меньше, а недостающий аустенитный каркас обеспечивают марганец и азот. Прочность при этом не страдает: по пределу текучести 201 даже превосходит 304. Платят за 304 не за прочность, а за коррозионную стойкость в хлоридных и кислотных средах, где 201 уступает.</p>

<h2>Где AISI 201 подходит</h2>
