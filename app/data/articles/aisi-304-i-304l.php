<h2>Что происходит при сварке и почему важен углерод</h2>
<p>Когда обычную AISI 304 нагревают примерно до 425–850 °C (в том числе в зоне около сварного шва), хром уходит к границам зёрен и связывается с углеродом в карбиды. Приграничные участки обедняются хромом и теряют стойкость: в агрессивной среде по ним начинается межкристаллитная коррозия (МКК). Это явление называют сенсибилизацией.</p>
<p>В AISI 304L углерода так мало, что карбиды практически не успевают образоваться. Поэтому шов и околошовная зона сохраняют коррозионную стойкость без последующей термообработки.</p>
<p>Платить за это приходится небольшим снижением прочности: предел прочности 304L не менее 485 МПа против 515 МПа у 304, предел текучести не менее 170 против 205 МПа. Для большинства конструкций этого достаточно.</p>

<h2>Когда брать AISI 304L</h2>
<ul>
<li>Сварные ёмкости, реакторы и трубопроводы, которые после сварки не отжигают.</li>
<li>Оборудование с большим количеством сварных швов: пищевое, химическое, фармацевтическое.</li>
<li>Изделия, которые работают в агрессивных средах и при этом сварены.</li>
<li>Криогенные применения: 304L сохраняет пластичность при низких температурах.</li>
</ul>

<h2>Когда достаточно обычной AISI 304</h2>
<ul>
<li>Сварки нет: детали штампуют, гнут, соединяют механически.</li>
<li>После сварки изделие проходит термообработку.</li>
<li>Нужна максимальная прочность из этой пары марок.</li>
<li>Среда нейтральная, а шов не критичен для долговечности.</li>
</ul>
