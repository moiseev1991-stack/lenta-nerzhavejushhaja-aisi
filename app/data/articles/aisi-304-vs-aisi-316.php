<h2>Частые ошибки при выборе</h2>
<ul>
<li><strong>Различать 304 и 316 магнитом.</strong> Обе марки аустенитные и в состоянии поставки не магнитятся, поэтому магнит их не различает. Достоверно определить марку можно по сертификату плавки или экспресс-анализом состава.</li>
<li><strong>Брать 316 «на всякий случай».</strong> Если среда не агрессивна, вы переплачиваете без выигрыша в сроке службы.</li>
<li><strong>Брать 304 для солёной среды из экономии.</strong> На поверхности появятся ржавые точки, и изделие придётся менять.</li>
<li><strong>Не учитывать сварку.</strong> Для сварных конструкций в агрессивных средах выбирают низкоуглеродистые версии AISI 304L и AISI 316L (углерод ≤ 0,03%): в них меньше риск межкристаллитной коррозии около шва. Подробнее: <a href="/spravochnik/aisi-304-i-304l/">304 и 304L</a>, <a href="/spravochnik/aisi-316-i-316l/">316 и 316L</a>.</li>
</ul>

