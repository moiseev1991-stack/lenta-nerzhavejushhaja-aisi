<h2>В чём главное отличие: молибден</h2>
<p>Нержавеющая сталь защищена тонким пассивным оксидным слоем на основе хрома. Хлориды (соль, морская вода, хлорсодержащие моющие средства и реагенты) разрушают этот слой в отдельных точках, и на поверхности появляется точечная (питтинговая) коррозия. Молибден встраивается в защитный слой и многократно повышает его стойкость к такому разрушению. Поэтому в солёной и хлорированной среде AISI 316 служит заметно дольше, чем 304.</p>
<p>Дополнительно 316 содержит больше никеля (10–14% против 8–10,5%), что тоже улучшает коррозионную стойкость и делает сталь стабильнее в кислотных средах (уксусной, фосфорной).</p>

<h2>Когда достаточно AISI 304</h2>
<ul>
<li>Оборудование пищевой промышленности без постоянного контакта с кислыми и солёными средами.</li>
<li>Бытовая техника, мойки, поручни, фасадные и интерьерные элементы в обычной атмосфере.</li>
<li>Монтажные ленты, хомуты, крепёж, кожухи.</li>
<li>Детали под штамповку, гибку и вытяжку: 304 универсальна и хорошо обрабатывается давлением.</li>
</ul>

