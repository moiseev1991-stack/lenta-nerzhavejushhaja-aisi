<h2>В чём разница на практике</h2>
<p>У обеих марок одинаковая основа: хром, никель и 2–3% молибдена. Именно молибден даёт стойкость к хлоридам, морской воде и кислотам, и тут 316 и 316L равны. Различается только углерод.</p>
<p>При сварке или любом нагреве в районе 425–850 °C углерод в обычной 316 связывает хром в карбиды на границах зёрен. Эти участки теряют стойкость, и в агрессивной среде у шва начинается межкристаллитная коррозия. В 316L углерода не более 0,03%, поэтому карбиды практически не образуются, а шов сохраняет свойства без термообработки.</p>
<p>Платой за это становится чуть более низкая прочность: Rm не менее 485 МПа у 316L против 515 МПа у 316.</p>

<h2>Когда брать AISI 316L</h2>
<ul>
<li>Сварные реакторы, ёмкости и трубопроводы в химической и фармацевтической промышленности.</li>
<li>Сварные конструкции для морской среды.</li>
<li>Оборудование для производства уксуса, соков, концентратов и других кислых пищевых сред.</li>
<li>Сварные трубопроводы и фланцы для кислых и хлоридных сред.</li>
</ul>

<h2>Когда достаточно AISI 316</h2>
