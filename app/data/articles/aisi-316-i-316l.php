<h2>А как же 316Ti</h2>
<p>AISI 316Ti (аналог 10Х17Н13М2Т) защищена от межкристаллитной коррозии другим способом: титан связывает углерод. Её выбирают, когда деталь одновременно работает в агрессивной среде и при повышенной температуре. При умеренных температурах преимуществ перед 316L у неё нет.</p>

