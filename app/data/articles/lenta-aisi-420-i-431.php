<h2>Как работают закаливаемые стали</h2>
<p>В отличие от аустенитных марок (304, 316), мартенситные стали упрочняются термообработкой. В отожжённом состоянии лента мягкая: её режут, гнут и штампуют. После закалки (для 420 нагрев примерно до 980–1050 °C и охлаждение) и отпуска деталь становится очень твёрдой и прочной. Поэтому ленту заказывают в мягком состоянии, штампуют деталь, а затем закаляют.</p>

<h2>Где применяют AISI 420</h2>
<ul>
<li>Кухонные, охотничьи и тактические ножи, скальпели и хирургические инструменты.</li>
<li>Лезвия бритв и станков.</li>
<li>Пружинные элементы, требующие высокой прочности.</li>
<li>Режущий инструмент для пищевой промышленности.</li>
<li>Детали арматуры насосов и клапанов, твёрдые шестерни и валы.</li>
</ul>
<p>Для лезвий толщиной 0,1–0,5 мм берут тонкую ленту, для ножей и инструмента 0,5–3,0 мм.</p>

<h2>Где применяют AISI 431</h2>
<ul>
<li>Оси и валы, насосные валы, детали арматуры.</li>
<li>Высокопрочный крепёж.</li>
<li>Зубчатые колёса для коррозионных сред.</li>
<li>Детали компрессоров и насосов в нефтегазовой промышленности.</li>
<li>Морское и авиационное приборостроение.</li>
</ul>
<p>Ленту 431 используют преимущественно для штамповки деталей с последующей термообработкой; типичные толщины 0,5–3,0 мм.</p>

<h2>Что выбрать: 420 или 431</h2>
<ul>
<li><strong>420</strong> нужна, когда главное — твёрдость и острая кромка после закалки (ножи, лезвия).</li>
<li><strong>431</strong> выбирают, когда важны прочность и вязкость вместе с лучшей коррозионной стойкостью.</li>
<li><strong>430</strong> не закаливается, но лучше сопротивляется атмосферной коррозии. См. <a href="/aisi-430/">лента AISI 430</a>.</li>
</ul>
