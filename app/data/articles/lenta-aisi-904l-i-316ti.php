<h2>Когда достаточно 316L</h2>
<p>В большинстве случаев: солёная среда, слабые и средние кислоты, сварные аппараты. Если условия умеренные, 316L справляется. Сравнение с 316: <a href="https://gkmetallinvest.ru/blog/aisi-316-i-316l/" target="_blank" rel="noopener">«AISI 316 и 316L» на основном сайте</a>.</p>

<h2>Когда нужна AISI 316Ti</h2>
<p>Эта сталь соединяет молибден с титановой стабилизацией. Титан связывает углерод, поэтому сталь не склонна к межкристаллитной коррозии при нагреве. Выбирайте 316Ti, когда деталь одновременно работает в агрессивной среде (хлориды, кислоты) и при длительном нагреве выше 450 °C, до 850 °C. Типичные области: теплообменники и реакторы в нефтехимии, трубопроводы перегретого пара, сульфатная варка в целлюлозно-бумажной промышленности.</p>
<p>Для умеренных температур в агрессивных средах предпочтительнее 316L, для высоких температур без агрессивных сред — 321.</p>

<h2>Когда нужна AISI 904L</h2>
<p>Это сталь «для экстремальных условий»: вдвое больше никеля и молибдена, чем у 316, плюс медь. Состав даёт исключительную стойкость к питтингу, щелевой коррозии и растрескиванию, а медь повышает стойкость к серной кислоте. Применяют её для:</p>
<ul>
<li>производства серной и фосфорной кислоты, отбеливателей;</li>
<li>оборудования для кислых и хлорсодержащих сред в нефтегазовой отрасли;</li>
<li>деталей, постоянно контактирующих с морской водой;</li>
<li>целлюлозно-бумажной промышленности (варка и отбелка целлюлозы);</li>
<li>производства минеральных удобрений и опреснительных установок.</li>
</ul>
<p>Обрабатывается сложнее обычных аустенитных сталей и заметно дороже 316L, поэтому выбирайте её только тогда, когда 316L и 316Ti не справляются.</p>

